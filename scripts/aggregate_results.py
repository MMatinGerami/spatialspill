"""Aggregate run outputs into the project-level tables and figures.

Reads every results/<hash>/ directory that has a config.yaml and either *_calibration.json
(real-data E1 runs) or benchmark_summary.csv (simulator benchmarks), and writes:

  results/summary/real_data_calibration.csv / .md   one row per run x dataset
  results/summary/simulator_benchmark.csv / .md    latest benchmark per config file
  results/summary/fig_calibration.png               NTC false-positive rates and simulator
                                                    coverage, side by side

Usage: uv run python scripts/aggregate_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = RES / "summary"


def real_data_rows() -> pd.DataFrame:
    rows = []
    for d in sorted(RES.glob("*/")):
        cfgp = d / "config.yaml"
        if not cfgp.exists():
            continue
        cfg = yaml.safe_load(cfgp.read_text())
        for cal in d.glob("*_calibration.json"):
            r = json.loads(cal.read_text())
            rows.append(
                {
                    "run": d.name,
                    "dataset": r["dataset"],
                    "estimator": r.get("estimator", cfg.get("estimator", "E1")),
                    "spatial_basis": cfg.get("spatial_basis", 0),
                    "strata": "+".join(cfg.get("strata", [])),
                    "tile_um": cfg.get("tile_um", 0) or 0,
                    "control_policy": cfg.get("control_policy", "ntc"),
                    "clean_controls": cfg.get("clean_controls", True),
                    "n_perm": cfg.get("n_perm"),
                    "n_tests": r["n_tests"],
                    "n_ntc_tests": r["n_ntc_tests"],
                    "ntc_p05": r["ntc_fraction_p_below_0.05"],
                    "ntc_q10": r["ntc_fraction_q_below_fdr"],
                    "ntc_p05_auto": r.get("ntc_p05_autonomous"),
                    "ntc_p05_r1": r.get("ntc_p05_ring1"),
                    "ntc_p05_r2": r.get("ntc_p05_ring2"),
                    "autonomous_hits": r["n_autonomous_hits"],
                    "auto_fdp_ntc": r.get("ntc_fdp_autonomous"),
                    "spillover_hits": r["n_spillover_hits"],
                    "spill_fdp_ntc": r.get("ntc_fdp_spillover"),
                    "mtime": cal.stat().st_mtime,
                }
            )
    df = pd.DataFrame(rows)
    if len(df):
        df = df.sort_values(["dataset", "mtime"]).drop(columns="mtime")
    return df


def benchmark_rows() -> pd.DataFrame:
    frames = []
    for d in sorted(RES.glob("*/")):
        f = d / "benchmark_summary.csv"
        if f.exists():
            s = pd.read_csv(f)
            s.insert(0, "run", d.name)
            s["mtime"] = f.stat().st_mtime
            frames.append(s)
    if not frames:
        return pd.DataFrame()
    df = pd.concat(frames, ignore_index=True)
    # keep the most recent run per (scenario set, estimator set) as identified by the run dir
    latest = df.groupby("run")["mtime"].max().sort_values().index[-3:]
    return df[df["run"].isin(latest)].drop(columns="mtime")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    real = real_data_rows()
    bench = benchmark_rows()
    real.to_csv(OUT / "real_data_calibration.csv", index=False)
    bench.to_csv(OUT / "simulator_benchmark.csv", index=False)
    md = [
        "# Summary tables",
        "",
        "Generated by scripts/aggregate_results.py. Numbers come from results/<hash>/.",
        "",
    ]
    md += [
        "## Real-data E1 runs: NTC calibration and hit counts",
        "",
        real.to_markdown(index=False) if len(real) else "(none)",
        "",
    ]
    md += [
        "## Simulator benchmark (latest runs)",
        "",
        bench.to_markdown(index=False) if len(bench) else "(none)",
        "",
    ]
    (OUT / "summary.md").write_text("\n".join(md) + "\n")

    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    if len(real):
        lab = (
            real["dataset"]
            + "\n"
            + real["strata"].str.replace("sample+cell_type", "s x ct")
            + real["tile_um"].apply(lambda t: f" {int(t)}um" if t else "")
        )
        axes[0].bar(range(len(real)), real["ntc_p05"], color="grey")
        axes[0].axhline(0.05, color="crimson", ls="--", lw=1)
        axes[0].set_xticks(range(len(real)))
        axes[0].set_xticklabels(lab, fontsize=7, rotation=45, ha="right")
        axes[0].set_ylabel("NTC pseudo-targets with p < 0.05")
        axes[0].set_title("Real data: non-targeting calibration (E1)")
    if len(bench):
        b = (
            bench[(bench["kind"] == "spillover")]
            .groupby(["estimator", "scenario"], as_index=False)["null_cov95"]
            .mean()
        )
        piv = b.pivot(index="scenario", columns="estimator", values="null_cov95")
        piv.plot(kind="bar", ax=axes[1], width=0.8)
        axes[1].axhline(0.95, color="crimson", ls="--", lw=1)
        axes[1].set_ylabel("95% CI coverage of null spillover pairs")
        axes[1].set_title("Simulator: interval coverage")
        axes[1].set_ylim(0.5, 1.0)
        axes[1].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT / "fig_calibration.png", dpi=130)
    print((OUT / "summary.md").read_text()[:3000])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
